import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const outDir = path.join(root, 'src', 'generated');
const outFile = path.join(outDir, 'asset-version.ts');
const raw = process.env.GITHUB_SHA || '';
const sha = raw.replace(/[^a-f0-9]/gi, '').slice(0, 12) || 'dev';

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(
  outFile,
  `// Generated by scripts/generate-asset-version.mjs — do not edit.\nexport const ASSET_VERSION = '${sha}';\n`,
  'utf8',
);
console.log(`asset-version: ${sha}`);

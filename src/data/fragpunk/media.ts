function normalizePath(pathname: string): string {
  let path = pathname || '/';
  if (!path.startsWith('/')) path = `/${path}`;
  if (path !== '/' && !path.endsWith('/')) path = `${path}/`;
  return path;
}

export function resolveFragpunkPageMedia(pathname: string): {
  heroId?: FragPunkScreenshotId;
  sectionImages: Partial<Record<string, FragPunkScreenshotId>>;
  ogKey?: FragPunkOgKey;
} {
  const path = normalizePath(pathname);
  return {
    heroId: PAGE_HERO[path],
    sectionImages: PAGE_SECTION_IMAGES[path] ?? {},
    ogKey: PAGE_OG[path],
  };
}

export function resolveFragpunkOg(pathname: string): { ogImage?: string; ogImageAlt?: string } {
  const { ogKey, heroId } = resolveFragpunkPageMedia(pathname);
  if (ogKey) {
    const hero = heroId ? fragpunkScreenshot(heroId) : undefined;
    return {
      ogImage: fragpunkOgImage(ogKey),
      ogImageAlt: hero?.alt,
    };
  }
  return {};
}
